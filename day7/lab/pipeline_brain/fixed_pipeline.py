from pyspark.sql.functions import sum, count, max, coalesce, avg, collect_set, distinct, min

def build_merchant_performance(spark, silver_path, output_path, run_date):
    """Build merchant performance Gold table with error handling."""
    try:
        logger.info(f"[GOLD] Building merchant_performance table")

        # Read Silver layer data
        silver_df = spark.read.parquet(silver_path).filter(col("date") == run_date)

        # Calculate total revenue, transaction count, and failure rate
        merchant_performance_df = silver_df.groupBy("merchant_id", "merchant_name", "category", "city", "date") \
           .agg(
                sum(when(col("status") == "COMPLETED", col("amount")).otherwise(0)).alias("total_revenue"),
                count("*").alias("txn_count"),
                (count(when(col("status") == "FAILED", 1)) / count("*") * 100).alias("failure_rate_pct")
            )

        # Write to Gold layer
        merchant_performance_df.write.mode("overwrite").partitionBy("date").parquet(output_path)
        logger.info(f"[GOLD] merchant_performance written to {output_path}")

    except Exception as e:
        logger.error(f"[GOLD] ERROR building merchant_performance: {str(e)}")
        raise

def build_customer_ltv(spark, silver_path, output_path):
    """Build customer LTV Gold table with error handling."""
    try:
        logger.info(f"[GOLD] Building customer_ltv table")

        # Read Silver layer data
        silver_df = spark.read.parquet(silver_path)

        # Calculate LTV metrics
        customer_ltv_df = silver_df.filter(col("status") == "COMPLETED") \
            .groupBy("customer_id") \
           .agg(
                sum("amount").alias("total_spent"),
                count("*").alias("total_txns"),
                avg("amount").alias("avg_txn_value"),
                min("transaction_date").alias("first_txn_date"),
                max("transaction_date").alias("last_txn_date"),
                coalesce(collect_set("payment_method")).alias("preferred_payment_method")
            )

        # Write to Gold layer
        customer_ltv_df.write.mode("overwrite").parquet(output_path)
        logger.info(f"[GOLD] customer_ltv written to {output_path}")

    except Exception as e:
        logger.error(f"[GOLD] ERROR building customer_ltv: {str(e)}")
        raise

def build_daily_summary(spark, silver_path, output_path, run_date):
    """Build daily summary Gold table with error handling."""
    try:
        logger.info(f"[GOLD] Building daily_summary table")

        # Read Silver layer data for the specific date
        silver_df = spark.read.parquet(silver_path).filter(col("date") == run_date)

        # Calculate daily summary metrics
        daily_summary_df = silver_df.groupBy("date") \
            .agg(
                sum(when(col("status") == "COMPLETED", col("amount")).otherwise(0)).alias("total_revenue"),
                count("*").alias("total_txns"),
                count(distinct("customer_id")).alias("unique_customers"),
                count(distinct("merchant_id")).alias("unique_merchants"),
                (count(when(col("status") == "FAILED", 1)) / count("*") * 100).alias("failure_rate_pct")
            )

        # Write to Gold layer
        daily_summary_df.write.mode("overwrite").partitionBy("date").parquet(output_path)
        logger.info(f"[GOLD] daily_summary written to {output_path}")

    except Exception as e:
        logger.error(f"[GOLD] ERROR building daily_summary: {str(e)}")
        raise

def run_gold(spark, silver_path, gold_output_dir, run_date):
    """Execute all Gold layer builds with error handling."""
    try:
        logger.info("=" * 60)
        logger.info("Building Gold layer tables")
        logger.info("=" * 60)

        # Define output paths for each Gold table
        merchant_performance_output_path = f"{gold_output_dir}/merchant_performance"
        customer_ltv_output_path = f"{gold_output_dir}/customer_ltv"
        daily_summary_output_path = f"{gold_output_dir}/daily_summary"

        # Build each Gold table
        build_merchant_performance(spark, silver_path, merchant_performance_output_path, run_date)
        build_customer_ltv(spark, silver_path, customer_ltv_output_path)
        build_daily_summary(spark, silver_path, daily_summary_output_path, run_date)

        # Write run metadata summary to JSON
        run_metadata = {
            "run_date": run_date,
            "silver_path": silver_path,
            "gold_output_dir": gold_output_dir,
            "tables": [
                {"name": "merchant_performance", "path": merchant_performance_output_path},
                {"name": "customer_ltv", "path": customer_ltv_output_path},
                {"name": "daily_summary", "path": daily_summary_output_path}
            ]
        }

        logger.info("All Gold tables built successfully")
        return run_metadata

    except Exception as e:
        logger.error(f"GOLD LAYER FAILED: {str(e)}")
        raise

