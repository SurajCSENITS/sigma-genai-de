from pyspark.sql import SparkSession
from pyspark.sql.functions import col, broadcast, when, current_timestamp, lit
from pyspark.sql.types import StringType, FloatType, DateType
import json
import os
import logging

# Configure logging
logging.basicConfig(level=logging.INFO)
logger = logging.getLogger(__name__)

def ingest_bronze(spark, input_path, output_path, run_date, run_id):
    """Ingest raw CSV data into Bronze layer with error handling."""
    try:
        logger.info(f"[BRONZE] Starting ingestion from {input_path}")

        # Read raw CSV files with all columns as strings
        transactions_df = (spark.read.option("header", "true")
                          .option("inferSchema", "false")
                           .csv(input_path))

        input_count = transactions_df.count()
        logger.info(f"[BRONZE] Ingested {input_count} records")

        # Add metadata columns
        transactions_df = (transactions_df.withColumn("ingestion_timestamp", current_timestamp())
                           .withColumn("source_file", lit(os.path.basename(input_path)))
                           .withColumn("pipeline_run_id", lit(run_id)))

        # Write as Parquet partitioned by date
        transactions_df.write.mode('overwrite').partitionBy('transaction_date').parquet(output_path)
        logger.info(f"[BRONZE] Successfully wrote {input_count} records to {output_path}")

        return {"status": "SUCCESS", "record_count": input_count}

    except Exception as e:
        logger.error(f"[BRONZE] ERROR during ingestion: {str(e)}")
        raise

def transform_silver(spark, bronze_path, merchants_path, output_path, run_date):
    """Transform Bronze data to Silver layer with error handling."""
    try:
        logger.info(f"[SILVER] Starting transformation from {bronze_path}")

        # Read Bronze Parquet with partition pruning on run_date
        transactions_df = (spark.read.parquet(bronze_path)
                           .where(col("transaction_date") == run_date)
                            .cache())

        bronze_count = transactions_df.count()
        logger.info(f"[SILVER] Read {bronze_count} records from Bronze")

        # Read merchants data and cache it
        merchants_df = (spark.read.option("header", "true")
                        .csv(merchants_path)
                         .withColumn("merchant_id", col("merchant_id").cast(StringType()))
                        .cache())

        merchant_count = merchants_df.count()
        logger.info(f"[SILVER] Loaded {merchant_count} merchant records")

        # Cast columns to correct types
        transactions_df = (transactions_df.withColumn("amount", col("amount").cast(FloatType()))
                            .withColumn("transaction_date", col("transaction_date").cast(DateType()))
                           .withColumn("transaction_id", col("transaction_id").cast(StringType()))
                           .withColumn("merchant_id", col("merchant_id").cast(StringType())))

        # Filter: remove records where transaction_id is NULL or amount < 0
        transactions_df = transactions_df.filter((col("transaction_id").isNotNull()) & (col("amount") >= 0))
        filtered_count = transactions_df.count()
        logger.info(f"[SILVER] After filter: {filtered_count} records (removed {bronze_count - filtered_count})")

        # Deduplicate: if same transaction_id appears twice, keep the record with latest ingestion_timestamp
        deduped_transactions_df = (transactions_df.orderBy(col("transaction_id"), col("ingestion_timestamp").desc())
                                   .dropDuplicates(["transaction_id"]))

        dedup_count = deduped_transactions_df.count()
        logger.info(f"[SILVER] After dedup: {dedup_count} records (removed {filtered_count - dedup_count} duplicates)")

        # Enrich: join transactions with merchants on merchant_id to get merchant_name, category, city
        enriched_transactions_df = (deduped_transactions_df.join(broadcast(merchants_df), deduped_transactions_df.merchant_id == merchants_df.merchant_id, "left_outer")
                                   .withColumn("quality_flag",
                                               when(col("merchant_id").isNull(), "UNMATCHED").otherwise("CLEAN")))

        final_count = enriched_transactions_df.count()
        logger.info(f"[SILVER] After enrichment: {final_count} records")

        # Write as Parquet partitioned by date
        enriched_transactions_df.write.mode('overwrite').partitionBy('transaction_date').parquet(output_path)
        logger.info(f"[SILVER] Successfully wrote {final_count} records to {output_path}")

        return {"status": "SUCCESS", "record_count": final_count}

    except Exception as e:
        logger.error(f"[SILVER] ERROR during transformation: {str(e)}")
        raise

def main(input_path, merchants_path, bronze_path, silver_path, gold_output_dir, run_date, run_id):
    """Main pipeline execution with error handling."""
    try:
        # Initialize Spark session
        spark = (SparkSession.builder
                .appName("Sigma DataTech Transaction Analytics Pipeline")
                 .getOrCreate())

        logger.info("=" * 60)
        logger.info("Pipeline execution started")
        logger.info(f"Run date: {run_date} | Run ID: {run_id}")
        logger.info("=" * 60)

        # Ingest Bronze layer
        bronze_result = ingest_bronze(spark, input_path, bronze_path, run_date, run_id)

        # Transform Silver layer
        silver_result = transform_silver(spark, bronze_path, merchants_path, silver_path, run_date)

        # Write run metadata summary to a JSON file
        run_metadata = {
            "run_date": run_date,
            "run_id": run_id,
            "status": "COMPLETED",
            "bronze_records": bronze_result["record_count"],
            "silver_records": silver_result["record_count"]
        }

        metadata_path = f"{gold_output_dir}/run_{run_id}.json"
        with open(metadata_path, "w") as f:
            json.dump(run_metadata, f, indent=2)

        logger.info(f"Run metadata saved to {metadata_path}")
        logger.info("=" * 60)
        logger.info("Pipeline execution completed successfully")
        logger.info("=" * 60)

        return run_metadata

    except Exception as e:
        logger.error(f"PIPELINE FAILED: {str(e)}")
        raise

